use crate::{Observation, Transport, paging};
use std::collections::BTreeMap;
pub(crate) fn read(http: &mut impl Transport, zone: &str, out: &mut BTreeMap<String, Observation>) {
    let base = format!("/zones/{zone}");
    out.insert(
        "dns_records".into(),
        paging::list(
            http,
            &format!("{base}/dns_records?order=name"),
            "id",
            &[
                "id",
                "name",
                "type",
                "content",
                "ttl",
                "proxied",
                "modified_on",
            ],
            false,
        ),
    );
    out.insert(
        "worker_routes".into(),
        paging::list(
            http,
            &format!("{base}/workers/routes"),
            "id",
            &["id", "pattern", "script"],
            true,
        ),
    );
    out.insert(
        "dnssec".into(),
        paging::object(
            http,
            &format!("{base}/dnssec"),
            &[
                "status",
                "ds",
                "digest",
                "digest_type",
                "key_tag",
                "algorithm",
                "modified_on",
            ],
        ),
    );
    out.insert(
        "security_txt".into(),
        paging::object(
            http,
            &format!("{base}/security-center/securitytxt"),
            &[
                "enabled",
                "contact",
                "expires",
                "canonical",
                "policy",
                "preferred_languages",
            ],
        ),
    );
    out.insert(
        "bot_management".into(),
        paging::object(
            http,
            &format!("{base}/bot_management"),
            &[
                "fight_mode",
                "crawler_protection",
                "ai_bots_protection",
                "enable_js",
                "sbfm_verified_bots",
            ],
        ),
    );
    for setting in ["ssl", "min_tls_version", "always_use_https"] {
        out.insert(
            setting.into(),
            paging::object(
                http,
                &format!("{base}/settings/{setting}"),
                &["id", "value"],
            ),
        );
    }
}
